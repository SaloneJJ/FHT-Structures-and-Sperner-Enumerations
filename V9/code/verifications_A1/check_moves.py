#!/usr/bin/env python3
"""check_moves.py -- checks of Section 8 of Article I (morphisms, Omega_1, edge toggles, connectivity,
restricted descent), recomputed with fht_moves.py.  Deterministic: the classes are generated by closure
from the star and sorted by canonical form; the random descents use the seed given on the command line.

Usage:  python3 check_moves.py [--vmax 6] [--seed 2026] [--descents 3]
"""
import argparse, random, time, itertools, sys
from collections import defaultdict, Counter
from fht_moves import *

ap = argparse.ArgumentParser()
ap.add_argument("--vmax", type=int, default=6)
ap.add_argument("--seed", type=int, default=2026)
ap.add_argument("--descents", type=int, default=3)
a = ap.parse_args()
T0 = time.time()
def log(*x):
    print(*x, flush=True)

# ---------------------------------------------------------------- classes by closure from the star
classes = {}          # v -> {canon: representative tree on {1..v}}
for v in range(1, a.vmax + 1):
    V = frozenset(range(1, v + 1))
    s = star(V)
    reps = {canon(s): s}
    todo = [s]
    while todo:
        t = todo.pop()
        for x, info in interior_moves(t):
            c = canon(x)
            if c not in reps:
                reps[c] = x; todo.append(x)
    classes[v] = dict(sorted(reps.items()))
    log(f"v={v}: {len(reps)} classes by closure of the interior moves from the star ({time.time()-T0:.0f}s)")
log("expected 1, 1, 4, 23, 231, 16947")

# ---------------------------------------------------------------- validity and inverses
def kappa(t): return len(realization(t))

def check_result(x, V):
    ok = check_axioms(x, V)
    back = tree_from_realization(V, realization(x))
    ok = ok and back is not None and canon_lab(back) == canon_lab(x)
    return ok

def canon_lab(t):
    """labelled identity: the realization"""
    return realization(t) if not isinstance(t, int) else ("pt", t)

INV = {"T1+": "T1-", "T1-": "T1+", "T2+": "T2-", "T2-": "T2+"}
def stats_moves(vrange, label):
    cnt = Counter(); bad = Counter(); dep = Counter()
    for v in vrange:
        V = frozenset(range(1, v + 1))
        for c, t in classes[v].items():
            if isinstance(t, int): continue
            R0 = realization(t); H0 = hierarchy(t); d0 = depth(t)
            for x, info in interior_moves(t):
                k = info[0]
                if k in ("T1+", "T1-"): cnt[(k, info[2])] += 1
                else: cnt[k] += 1
                if not check_result(x, V): bad["axioms/decomposition", k] += 1
                # inverse: t among the results of the inverse kind, at the same component, from x
                node = find_node(x, info[1])
                gen = {"T1+": moves_th1m, "T1-": moves_th1p, "T2+": moves_th2m, "T2-": moves_th2p}[k]
                inv = [y for y, j in gen(x, node) if realization(y) == R0]
                if not inv: bad["no inverse", k] += 1
                if k in ("T2+", "T2-") and len(inv) != 1: bad["inverse not unique", k] += 1
                if k in ("T1+", "T1-"):
                    if hierarchy(x) != H0: bad["T1 changes the hierarchy", k] += 1
                    if depth(x) != d0: bad["T1 changes the depth", k] += 1
                if k == "T2-":
                    dep["T2-", "<=" if depth(x) <= d0 else ">"] += 1
                    if depth(x) < d0: dep["T2-", "strict"] += 1
                if k == "T2+":
                    dep["T2+", ">=" if depth(x) >= d0 else "<"] += 1
                    if depth(x) > d0: dep["T2+", "strict"] += 1
                if k in ("T2+", "T2-"):
                    n0 = find_node(t, info[1]); n1 = find_node(x, info[1])
                    if reduced_host_canon(n0) != reduced_host_canon(n1): bad["reduced host changed", k] += 1
                dk = kappa(x) - kappa(t)
                exp = 1 if k == "T2+" else -1 if k == "T2-" else (1 - info[2]) if k == "T1+" else (info[2] - 1)
                if dk != exp: bad["kappa variation", k] += 1
    log(f"[{label}] moves:", dict(sorted(cnt.items(), key=str)))
    log(f"[{label}] depth:", dict(dep))
    log(f"[{label}] failures:", dict(bad) if bad else "none")

stats_moves(range(2, min(5, a.vmax) + 1), "validity v<=5")
if a.vmax >= 6:
    stats_moves([6], "validity v=6 (exhaustive)")
log(f"({time.time()-T0:.0f}s)")

# ---------------------------------------------------------------- Omega_1
for v in range(2, a.vmax + 1):
    V = frozenset(range(1, v + 1)); x = v + 1
    add = rem = blk = 0; bad = 0
    for c, t in classes[v].items():
        for y, info in omega_plus(t, x):
            add += 1
            if not check_axioms(y, V | {x}): bad += 1
            back, _ = omega_minus(y)
            if not any(realization(z) == realization(t) and info2[1] == x for z, info2 in back): bad += 1
        al, b = omega_minus(t)
        rem += len(al); blk += b
        for y, info in al:
            W = V - {info[1]}
            if not check_axioms(y, W): bad += 1
            ok = any(realization(z) == realization(t) for z, j in omega_plus(y, info[1]))
            if not ok: bad += 1
    log(f"Omega_1, v={v}: additions {add}, allowed removals {rem}, blocked removals {blk}, failures {bad}")
t1 = classes[1][next(iter(classes[1]))]
log("degenerate: additions from F_1:", len(omega_plus(t1, 2)), "; removals from St_2:", len(degenerate_minus(star({1, 2}))))

# global connectivity with Omega_1 (classes 1..vmax)
allc = [(v, c) for v in classes for c in classes[v]]
idx = {k: i for i, k in enumerate(allc)}
par = list(range(len(allc)))
def f(i):
    while par[i] != i: par[i] = par[par[i]]; i = par[i]
    return i
def u(i, j):
    i, j = f(i), f(j)
    if i != j: par[i] = j
for v in classes:
    for c, t in classes[v].items():
        for x, info in interior_moves(t): u(idx[(v, c)], idx[(v, canon(x))])
        if v < a.vmax:
            for y, info in omega_plus(t, v + 1):
                cy = canon(y)
                if (v + 1, cy) in idx: u(idx[(v, c)], idx[(v + 1, cy)])
ncomp_all = len({f(i) for i in range(len(allc))})
sub = [i for i, (v, c) in enumerate(allc) if v >= 2]
log(f"classes 1..{a.vmax}: {len(allc)}, components with Omega_1 and the degenerate moves: {ncomp_all}")
par = list(range(len(allc)))
for v in classes:
    if v < 2: continue
    for c, t in classes[v].items():
        for x, info in interior_moves(t): u(idx[(v, c)], idx[(v, canon(x))])
        if v < a.vmax:
            for y, info in omega_plus(t, v + 1): u(idx[(v, c)], idx[(v + 1, canon(y))])
log(f"classes 2..{a.vmax}: {len(sub)}, components without the degenerate moves: {len({f(i) for i in sub})}")
log(f"({time.time()-T0:.0f}s)")

# ---------------------------------------------------------------- edge toggles
def is_fht_realization(V, E):
    t = tree_from_realization(V, E)
    return t is not None and check_axioms(t, V) and realization(t) == frozenset(E)

for v in range(2, a.vmax + 1):
    V = frozenset(range(1, v + 1))
    nadd = ndel = 0; bad = 0
    allsets = [frozenset(s) for k in range(2, v + 1) for s in itertools.combinations(sorted(V), k)]
    for c, t in classes[v].items():
        R = realization(t)
        adds = {R | {s} for s in allsets if s not in R and is_fht_realization(V, R | {s})}
        dels = {R - {s} for s in R if is_fht_realization(V, R - {s})}
        nadd += len(adds); ndel += len(dels)
        tog = set()
        for x, info in interior_moves(t):
            k = info[0]
            if k in ("T2+", "T2-") or (k in ("T1+", "T1-") and info[2] == 0):
                tog.add(realization(x))
        if tog != adds | dels: bad += 1
    log(f"edge toggles, v={v}: additions {nadd}, deletions {ndel}, classes where they differ from the moves: {bad}")
log(f"({time.time()-T0:.0f}s)")

# ---------------------------------------------------------------- connectivity of the quotient graphs
def ncomp(v, kinds, maxrho=None):
    keys = list(classes[v]); ix = {k: i for i, k in enumerate(keys)}; p = list(range(len(keys)))
    def g(i):
        while p[i] != i: p[i] = p[p[i]]; i = p[i]
        return i
    nm = 0
    for c, t in classes[v].items():
        for x, info in interior_moves(t, kinds=kinds, maxrho=maxrho):
            nm += 1
            cx = canon(x)
            if cx not in ix: raise SystemExit("a move leaves the set of classes")
            i, j = g(ix[c]), g(ix[cx])
            if i != j: p[i] = j
    return len({g(i) for i in range(len(keys))}), nm
ALL = ("T1+", "T1-", "T2-", "T2+")
rows = [("all moves", ALL, None), ("distance <= 1 from the root", ALL, 1), ("root only", ALL, 0),
        ("Theta_1 only", ("T1+", "T1-"), None), ("Theta_2 only", ("T2+", "T2-"), None)]
for name, kinds, mr in rows:
    log(f"components, {name}: " + ", ".join(f"v={v}: {ncomp(v, kinds, mr)[0]}" for v in range(2, a.vmax + 1)))
tot = Counter()
for v in range(2, a.vmax + 1):
    for c, t in classes[v].items():
        for x, info in interior_moves(t):
            tot["T1+-" if info[0] in ("T1+", "T1-") else info[0]] += 1
log(f"moves from the class representatives with 2<=v<={a.vmax}:", dict(tot))
log(f"({time.time()-T0:.0f}s)")

# ---------------------------------------------------------------- restricted descent (Theorem descent)
def descending_th1(t, n):
    return [x for x, info in moves_th1p(t, n) if info[2] == 2] + [x for x, info in moves_th1m(t, n) if info[2] == 0]

def restricted_step(t, rng):
    """the choice of the proof of Theorem descent: at the root if its host has >= 2 edges,
    otherwise at a non-leaf child of the root whose host has >= 2 edges, otherwise the explosion
    on (root, c) with eps = Ch(c)."""
    R = t
    if len(R.E) >= 2:
        opts = descending_th1(t, R); where = 0
    else:
        kids = [c for c in R.ch.values() if not isinstance(c, int)]
        big = [c for c in kids if len(c.E) >= 2]
        if big:
            c = rng.choice(big); opts = descending_th1(t, c); where = 1
        else:
            c = rng.choice(kids)
            opts = [x for x, info in moves_th2m(t, R) if info[2] == c.V and info[3] == frozenset(c.ch)]
            where = 0
    if not opts: return None, None
    return rng.choice(opts), where

rng = random.Random(a.seed)
nd = 0; bad = Counter(); steps = 0
for v in range(2, a.vmax + 1):
    V = frozenset(range(1, v + 1)); st = realization(star(V))
    for c, t in classes[v].items():
        for r in range(a.descents):
            x = t; k0 = kappa(t); n = 0
            while realization(x) != st:
                y, where = restricted_step(x, rng)
                if y is None: bad["no restricted descending move"] += 1; break
                if not check_axioms(y, V): bad["axioms"] += 1
                if kappa(y) != kappa(x) - 1: bad["kappa"] += 1
                x = y; n += 1
            if n != k0 - 1: bad["length != kappa-1"] += 1
            nd += 1; steps += n
log(f"restricted descents (seed {a.seed}, {a.descents} per class, 2<=v<={a.vmax}): {nd} descents, {steps} steps, failures:", dict(bad) if bad else "none")
log(f"total time {time.time()-T0:.0f}s")
