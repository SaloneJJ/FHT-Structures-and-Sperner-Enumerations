#!/usr/bin/env python3
"""census_s4.py -- census of the FHTs whose automorphism group contains S4 (Article I, Section 6, census),
recomputed independently of the program of the first version (which was not kept).

Method (the one described in the article): for each faithful action of S4 on v points (a multiset of
orbits S4/K with trivial total kernel), the S4-invariant FHTs are generated by the recursive
decomposition: an invariant partition of the vertices into at least two blocks, an invariant connected
clutter on the blocks, and for each orbit of blocks an FHT on a representative block invariant under its
stabilizer, transported to the other blocks of the orbit.  Isomorphism classes are decided by the canonical
form of fht_moves.py (all relabellings).  |Aut| is computed by testing all permutations of V.

Usage:  python3 census_s4.py 4 5 6 7
"""
import itertools, sys, time
from collections import Counter, defaultdict
from fht_moves import Node, realization, canon, admissible, conn_components

# ------------------------------------------------------------------ S4, its subgroups, its faithful actions
S4 = [tuple(p) for p in itertools.permutations(range(4))]
def mul(a, b): return tuple(a[b[i]] for i in range(len(b)))          # (a*b)(i) = a(b(i))
def inv(a):
    r = [0] * len(a)
    for i, x in enumerate(a): r[x] = i
    return tuple(r)
ID = tuple(range(4))
def closure(gens):
    G = {ID}; frontier = [ID]
    while frontier:
        new = []
        for g in frontier:
            for h in gens:
                k = mul(g, h)
                if k not in G: G.add(k); new.append(k)
        frontier = new
    return frozenset(G)
subs = set()
for a in S4:
    for b in S4:
        subs.add(closure([a, b]))
subs = list(subs)
def conj_class(H): return frozenset(frozenset(mul(mul(g, h), inv(g)) for h in H) for g in S4)
classes_sub = {}
for H in subs: classes_sub.setdefault(conj_class(H), H)
SUB = sorted(classes_sub.values(), key=lambda H: (len(H), sorted(H)))
assert len(SUB) == 11, len(SUB)

def coset_action(H):
    """S4 acting on left cosets gH: returns list of cosets and the permutation of each g"""
    cos = []
    for g in S4:
        c = frozenset(mul(g, h) for h in H)
        if c not in cos: cos.append(c)
    perm = {g: tuple(cos.index(frozenset(mul(g, x) for x in c)) for c in cos) for g in S4}
    return cos, perm

def faithful_actions(v):
    out = []
    sizes = [(24 // len(H), i) for i, H in enumerate(SUB)]
    def rec(start, rest, chosen):
        if rest == 0:
            # kernel = intersection of the cores
            ker = set(S4)
            for i in chosen:
                H = SUB[i]; core = set(S4)
                for g in S4: core &= {mul(mul(g, h), inv(g)) for h in H}
                ker &= core
            if ker == {ID}: out.append(tuple(chosen))
            return
        for j in range(start, len(sizes)):
            s, i = sizes[j]
            if s <= rest: rec(j, rest - s, chosen + [i])
    rec(0, v, [])
    return out

def action_perms(chosen):
    """the image of S4 in Sym(V), V = 1..v, for the action given by a list of subgroup indices"""
    blocks = []; off = 1
    for i in chosen:
        cos, perm = coset_action(SUB[i]); blocks.append((off, perm, len(cos))); off += len(cos)
    G = []
    for g in S4:
        p = {}
        for (o, perm, n) in blocks:
            for k in range(n): p[o + k] = o + perm[g][k]
        G.append(p)
    return G

# ------------------------------------------------------------------ invariant FHTs
def set_partitions(lst):
    if not lst:
        yield []; return
    first, rest = lst[0], lst[1:]
    for part in set_partitions(rest):
        for i in range(len(part)):
            yield part[:i] + [[first] + part[i]] + part[i + 1:]
        yield [[first]] + part

def img(g, S): return frozenset(g[x] for x in S)

def transport(t, g):
    if isinstance(t, int): return g[t]
    ch = {}
    for k, c in t.ch.items():
        c2 = transport(c, g); ch[img(g, k)] = c2
    E = {frozenset(img(g, k) for k in e) for e in t.E}
    return Node(ch, E)

def key_tree(t):
    return ("pt", t) if isinstance(t, int) else realization(t)

def invariant_hosts(parts, G):
    """admissible hosts on the set `parts` (frozensets) invariant under G"""
    P = list(parts)
    allsub = [frozenset(c) for k in range(2, len(P) + 1) for c in itertools.combinations(P, k)]
    orbits = []; seen = set()
    for s in allsub:
        if s in seen: continue
        orb = frozenset(frozenset(img(g, x) for x in s) for g in G)
        seen |= orb; orbits.append(orb)
    orbits.sort(key=lambda o: -len(next(iter(o))))
    res = []
    def ok_add(chosen, orb):
        for o in chosen:
            for e in o:
                for f in orb:
                    if e <= f or f <= e: return False
        # inside the orbit itself
        for e in orb:
            for f in orb:
                if e != f and e <= f: return False
        return True
    def rec(i, chosen):
        if i == len(orbits):
            if chosen:
                E = set().union(*chosen)
                if admissible(frozenset(P), E): res.append(E)
            return
        rec(i + 1, chosen)
        if ok_add(chosen, orbits[i]): rec(i + 1, chosen + [orbits[i]])
    rec(0, [])
    return res

MEMO = {}
def inv_trees(Vs, G):
    """all FHT trees on the set Vs invariant under G (a list of dicts restricted to Vs)"""
    Vs = frozenset(Vs)
    Gr = [{x: g[x] for x in Vs} for g in G]
    keyG = frozenset(tuple(sorted(g.items())) for g in Gr)
    key = (Vs, keyG)
    if key in MEMO: return MEMO[key]
    if len(Vs) == 1:
        MEMO[key] = [next(iter(Vs))]; return MEMO[key]
    Gu = [dict(t) for t in keyG]
    out = []
    for part in set_partitions(sorted(Vs)):
        if len(part) < 2: continue
        parts = frozenset(frozenset(p) for p in part)
        if any(img(g, p) not in parts for g in Gu for p in parts): continue
        hosts = invariant_hosts(parts, Gu)
        if not hosts: continue
        # orbits of parts
        orbs = []; seen = set()
        for p in sorted(parts, key=sorted):
            if p in seen: continue
            orb = {img(g, p) for g in Gu}; seen |= orb; orbs.append((p, orb))
        per_orbit = []
        for (p, orb) in orbs:
            stab = [g for g in Gu if img(g, p) == p]
            trees_p = inv_trees(p, stab)
            # coset representatives: for each part q of the orbit, one g with g(p) = q
            rep = {}
            for g in Gu:
                q = img(g, p)
                if q not in rep: rep[q] = g
            choices = []
            for tp in trees_p:
                choices.append({q: transport(tp, rep[q]) for q in orb})
            per_orbit.append(choices)
        for combo in itertools.product(*per_orbit):
            ch = {}
            for d in combo: ch.update(d)
            for E in hosts:
                out.append(Node(ch, E))
    MEMO[key] = out
    return out

def aut_order(t, V):
    R = realization(t); V = sorted(V); n = 0; odd = False
    for p in itertools.permutations(V):
        g = dict(zip(V, p))
        if {frozenset(g[x] for x in e) for e in R} == R:
            n += 1
            # parity
            seen = set(); par = 0
            for x in V:
                if x in seen: continue
                l = 0; y = x
                while y not in seen: seen.add(y); y = g[y]; l += 1
                par += l - 1
            if par % 2: odd = True
    return n, odd

if __name__ == "__main__":
    vs = [int(x) for x in sys.argv[1:]] or [4, 5, 6, 7]
    print("faithful actions of S4 on v points, v=4..9:", [len(faithful_actions(v)) for v in range(4, 10)])
    for v in vs:
        T0 = time.time()
        V = frozenset(range(1, v + 1))
        acts = faithful_actions(v)
        found = {}                       # canon -> (tree, action label)
        for chosen in acts:
            lab = "+".join(str(24 // len(SUB[i])) for i in chosen)
            G = action_perms(chosen)
            MEMO.clear()
            trees = inv_trees(V, G)
            new = 0
            for t in trees:
                c = canon(t)
                if c not in found: found[c] = (t, lab); new += 1
            print(f"v={v}, action {lab} (subgroups of orders {[len(SUB[i]) for i in chosen]}): {len(trees)} invariant labelled FHTs, {new} new classes ({time.time()-T0:.0f}s)", flush=True)
        orders = Counter(); s4_by_action = Counter(); s4_odd = 0; big = 0
        for c, (t, lab) in found.items():
            if v >= 8 and False: pass
            n, odd = aut_order(t, V)
            orders[n] += 1
            if n == 24:
                s4_by_action[lab] += 1
                if odd: s4_odd += 1
        print(f"v={v}: {len(found)} classes with Aut containing S4; |Aut| distribution: {dict(sorted(orders.items()))}")
        print(f"v={v}: Aut = S4: {orders[24]} ({dict(s4_by_action)}), of which sgn_V != 1: {s4_odd}; |Aut| = 48: {orders[48]}; |Aut| = 144: {orders[144]}; |Aut| > 1200: {sum(k for o, k in orders.items() if o > 1200)} ({time.time()-T0:.0f}s)", flush=True)

# ------------------------------------------------------------------ faster |Aut| for v >= 8 (Theorem autrec)
def aut_order_tree(t):
    """|Aut(F)| = |Gamma(root)| * prod |Aut(F_c)| (exact sequence of Theorem autrec), Gamma counted by brute
    force over the permutations of the children preserving their types and the host."""
    if isinstance(t, int): return 1
    keys = list(t.ch); cc = {k: canon(t.ch[k]) for k in keys}
    groups = defaultdict(list)
    for k in keys: groups[cc[k]].append(k)
    E = t.E; n = 0
    gl = list(groups.values())
    for perms in itertools.product(*[itertools.permutations(g) for g in gl]):
        m = {}
        for g, p in zip(gl, perms): m.update(zip(g, p))
        if {frozenset(m[k] for k in e) for e in E} == E: n += 1
    prod = 1
    for k in keys: prod *= aut_order_tree(t.ch[k])
    return n * prod
