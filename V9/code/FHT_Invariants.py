def gtex(name):
    if name == "{e}":
        return r"$\{e\}$"
    if name.startswith("group of order"):
        return name
    s = name.replace(" x ", r" \times ").replace(" wr ", r" \wr ")
    s = re.sub(r"([CSDAQV])(\d+)", r"\1_{\2}", s)
    return "$" + s + "$"


def tup(t):
    return "(" + ",".join(str(x) for x in t) + ")"


def fr(x):
    x = Fraction(x)
    return str(x.numerator) if x.denominator == 1 else f"{x.numerator}/{x.denominator}"


def st(s):
    return ["--", "--", "--"] if s is None else [str(s[0]), str(s[1]), fr(s[2])]


def tex_row(label, grp, order, k, orbs, inv, col7, P, L, I):
    return " & ".join([label, grp, str(order), str(k), tup(orbs), str(inv), col7] + st(P) + st(L) + st(I)) + r" \\"


def annex_A(data):
    lines, prev_v = [], 0
    for r in data:
        if r["v"] != prev_v and prev_v != 0:
            lines.append(r"\midrule")
        elif prev_v != 0:
            lines.append(r"\addlinespace[3pt]")
        prev_v = r["v"]
        lines.append(tex_row(r"\textbf{$\F_{%d}$}" % r["id"], gtex(r["aut"]), r["autn"], r["k"], r["orbs"], r["inv"],
                             tup(r["betti"]), r["P"], r["L"], r["I"]))
        if r["v"] == 1:
            continue
        root = r["hosts"][0]
        if r["N"] != 1:                          # non-flat: root host line, then the other components
            c7 = r"$%d\,|\,%d\,|\,\F_{%d}$" % (root["m"], root["nE"], root["flat"])
            lines.append(tex_row(r"\quad\textit{root}", gtex(root["gname"]), root["gamma"], len(root["orbs"]),
                                 root["orbs"], root["inv"], c7, root["P"], root["L"], root["I"]))
            groups, order = {}, []
            for h in r["hosts"][1:]:
                key = (h["depth"], h["ctype"])
                if key not in groups:
                    groups[key] = [h, 0]
                    order.append(key)
                groups[key][1] += 1
            for key in order:
                h, mu = groups[key]
                lab = r"\quad$\F_{%d}$" % h["ctype"]
                if key[0] > 1:
                    lab += r"$^{(%d)}$" % key[0]
                if mu > 1:
                    lab += r"$\,{\times}%d$" % mu
                c7 = r"$%d\,|\,%d\,|\,\F_{%d}$" % (h["m"], h["nE"], h["flat"])
                lines.append(tex_row(lab, gtex(h["gname"]), h["gamma"], len(h["orbs"]), h["orbs"], h["inv"], c7,
                                     h["P"], h["L"], h["I"]))
    return "\n".join(lines)


def powl(lst):
    c = Counter(lst)
    return r"\,".join(("$%d$" % k if m == 1 else "$%d^{%d}$" % (k, m)) for k, m in sorted(c.items(), reverse=True))


def annex_B(data):
    lines, prev = [], 0
    for r in data:
        if r["v"] == 1:
            continue
        if prev and r["v"] != prev:
            lines.append(r"\midrule")
        prev = r["v"]
        h = r["hosts"][0]
        prof = r"\; ".join(r"$\F_{%d}[%s]%s$" % (t, ",".join(map(str, sz)), (r"{\times}%d" % mu) if mu > 1 else "")
                           for (t, sz), mu in h["profile"])
        wt = "--" if r["N"] == 1 else powl(h["ewt"])
        lines.append(" & ".join([r"$\F_{%d}$" % r["id"], prof, powl(h["esz"]), wt, str(h["nP"]), str(h["nL"]),
                                 tup(h["eorb"]), tup(r["eorb"])]) + r" \\")
    return "\n".join(lines)


def separation(data):
    """Number of classes at each level of invariants (i)...(vi), per |V| and in total."""
    def sig(level, r):
        base = (r["v"], r["N"], r["nE"])
        a = (r["aut"], r["autn"], r["k"], tuple(r["orbs"]), r["inv"])
        b = tuple(r["betti"])
        g = (r["P"], r["L"], r["I"])
        hh = tuple(sorted((x["depth"], x["m"], x["nE"], x["flat"], x["gamma"], tuple(x["orbs"]), x["inv"],
                           x["P"], x["L"], x["I"]) for x in r["hosts"]))
        return {0: base, 1: base + a, 2: base + a + (b,), 3: base + a + (b, g), 4: base + a + (b, g, hh),
                5: base + a + (b, g, hh, tuple(r["eorb"]))}[level]
    cls = {v: [len({sig(l, r) for r in data if r["v"] == v}) for l in range(6)] for v in range(1, 6)}
    cls["tot"] = [len({sig(l, r) for r in data}) for l in range(6)]
    nf = {v: sum(1 for r in data if r["v"] == v) for v in range(1, 6)}
    return cls, nf


def sep_table(data):
    cls, nf = separation(data)
    mk = lambda label, n, c: r"%s & %d & %s \\" % (label, n, " & ".join(str(x) for x in c))
    tab = (r"\begin{tabular}{@{}lrrrrrrr@{}}" + "\n" + r"\toprule" + "\n"
           r" & number of FHTs & (i) & (ii) & (iii) & (iv) & (v) & (vi)\\" + "\n" + r"\midrule" + "\n"
           + "\n".join(mk(r"$\lvert V\rvert=%d$" % v, nf[v], cls[v]) for v in (3, 4, 5)) + "\n" + r"\midrule" + "\n"
           + mk(r"$\lvert V\rvert\le5$", len(data), cls["tot"]) + "\n" + r"\bottomrule" + "\n" + r"\end{tabular}")
    return tab, cls, nf


