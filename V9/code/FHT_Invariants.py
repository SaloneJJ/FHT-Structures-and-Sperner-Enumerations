def relabel(S, edges):
    vs = sorted(bits(S))
    pos = {x: i for i, x in enumerate(vs)}
    return len(vs), tuple(sorted(sum(1 << pos[x] for x in bits(e)) for e in edges))


def decompose(S, E):
    """S: vertex mask; E: edges inside S.  Returns (blocks, host, low): the 'blocks' are the children of the root, i.e. the connected components
    of the non-maximal edges ('low'); the host edges are the maximal edges, written as sets of block indices."""
    top = [e for e in E if not any(e != f and (e & f) == e for f in E)]
    low = [e for e in E if e not in top]
    parent = {x: x for x in bits(S)}

    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a
    for e in low:
        b = list(bits(e))
        for x in b[1:]:
            parent[find(x)] = find(b[0])
    comp = {}
    for x in bits(S):
        comp.setdefault(find(x), 0)
        comp[find(x)] |= 1 << x
    blocks = sorted(comp.values(), key=lambda m: min(bits(m)))
    host = []
    for e in top:
        idx = []
        for i, B in enumerate(blocks):
            if B & e:
                assert B & e == B, "a top edge is not a union of children"
                idx.append(i)
        host.append(frozenset(idx))
    assert len(set(host)) == len(host)
    return blocks, host, low


