# The three graphs of a hypergraph and eccentricities
# ======================================================================
def bfs_ecc(adj):
    ecc = []
    for s in range(len(adj)):
        d = [-1] * len(adj)
        d[s] = 0
        q = deque([s])
        while q:
            x = q.popleft()
            for y in adj[x]:
                if d[y] < 0:
                    d[y] = d[x] + 1
                    q.append(y)
        assert min(d) >= 0, "disconnected graph"
        ecc.append(max(d))
    return ecc


def graphs(m, hedges):
    """eccentricity lists of the primal graph P (on the m points), the edge graph L (on the edges: two edges
    adjacent iff they meet) and the incidence graph I (points + edges, point ~ edge iff incident)."""
    hedges = list(hedges)
    k = len(hedges)
    P = [set() for _ in range(m)]
    for e in hedges:
        for a in e:
            for b in e:
                if a != b:
                    P[a].add(b)
    L = [set() for _ in range(k)]
    for i in range(k):
        for j in range(k):
            if i != j and hedges[i] & hedges[j]:
                L[i].add(j)
    I = [set() for _ in range(m + k)]
    for j, e in enumerate(hedges):
        for a in e:
            I[a].add(m + j)
            I[m + j].add(a)
    return bfs_ecc(P), bfs_ecc(L), bfs_ecc(I)


def stat(ecc):
    """(radius, diameter = maximal eccentricity, mean eccentricity) -- exact fraction"""
    return (min(ecc), max(ecc), Fraction(sum(ecc), len(ecc)))


class Catalogue:
    """Isomorphism types of the FHT of the table (dictionary canonical form -> identifier)."""

    def __init__(self, rows):
        self.cert = {}
        for r in rows:
            k = canon_py(r["v"], list(r["edges"]))
            assert k not in self.cert, f"F_{r['id']} is isomorphic to F_{self.cert[k]}"
            self.cert[k] = r["id"]

    def typ(self, S, edges):
        v, E = relabel(S, edges)
        return 1 if v == 1 else self.cert[canon_py(v, list(E))]


def host_line(cat, S, E):
    """Parameters of the local host of the component with vertex set S and edges E."""
    blocks, host, low = decompose(S, E)
    m = len(blocks)
    types = [cat.typ(B, [e for e in low if e & B]) if popcount(B) > 1 else 1 for B in blocks]
    Hs = set(host)
    gens = [p for p in permutations(range(m))
            if all(types[p[i]] == types[i] for i in range(m)) and all(frozenset(p[i] for i in e) in Hs for e in host)]
    orb, seen = [], set()
    for i in range(m):
        if i in seen:
            continue
        o = sorted({p[i] for p in gens})
        seen |= set(o)
        orb.append(o)
    flat = cat.cert[canon_py(m, [sum(1 << i for i in e) for e in host])]
    pe, le, ie = graphs(m, host)
    hl = list(host)
    csz = [tuple(sorted(len(e) for e in hl if i in e)) for i in range(m)]
    prof = Counter((types[i], csz[i]) for i in range(m))
    esz = sorted((len(e) for e in hl), reverse=True)
    ewt = sorted((sum(popcount(blocks[i]) for i in e) for e in hl), reverse=True)
    nP = len({frozenset((a, b)) for e in hl for a in e for b in e if a < b})
    nL = sum(1 for i in range(len(hl)) for j in range(i) if hl[i] & hl[j])
    eorb, seen_e = [], set()
    for e in hl:
        if e in seen_e:
            continue
        o = {frozenset(p[i] for i in e) for p in gens}
        seen_e |= o
        eorb.append(len(o))
    return dict(profile=sorted(prof.items(), key=lambda kv: (kv[0][0], kv[0][1])), esz=esz, ewt=ewt, nP=nP, nL=nL,
                eorb=sorted(eorb, reverse=True), m=m, types=types, nE=len(host), flat=flat, gamma=len(gens),
                gname=group_name(set(gens), gens), orbs=sorted((len(o) for o in orb), reverse=True),
                inv=sum(1 for o in orb if len(o) == 1), P=stat(pe), L=stat(le), I=stat(ie),
                blocks=blocks, low=low, host=host)


def nodes_of(cat, S, E, depth=0, path=()):
    """all non-leaf components in preorder: (path, vertex set, edges, depth)"""
    out = [(path, S, E, depth)]
    hl = host_line(cat, S, E)
    for i, B in enumerate(hl["blocks"]):
        if popcount(B) > 1:
            out += nodes_of(cat, B, [e for e in hl["low"] if e & B], depth + 1, path + (i,))
    return out


