def betti_over_Q(v, E):
    try:
        import numpy as np          # only for this check
    except ImportError:
        return None                 # check skipped when numpy is absent
    F = set()
    for e in E:
        el = list(bits(e))
        for k in range(1, len(el) + 1):
            for c in combinations(el, k):
                F.add(sum(1 << x for x in c))
    byd = {}
    for f in F:
        byd.setdefault(popcount(f) - 1, []).append(f)
    top, rk = max(byd), {}
    for d in range(1, top + 1):
        rws, cls = sorted(byd.get(d - 1, [])), sorted(byd.get(d, []))
        idx = {f: i for i, f in enumerate(rws)}
        A = np.zeros((len(rws), len(cls)))
        for j, f in enumerate(cls):
            s = 0
            for x in range(v):
                if f >> x & 1:
                    A[idx[f ^ (1 << x)], j] = (-1) ** s
                    s += 1
        rk[d] = np.linalg.matrix_rank(A) if A.size else 0
    out = [len(byd.get(d, [])) - rk.get(d, 0) - rk.get(d + 1, 0) for d in range(top + 1)]
    while len(out) > 1 and out[-1] == 0:
        out.pop()
    return out


def run_checks(rows, data):
    byid = {d["id"]: d for d in data}
    bad = Counter()
    for r, d in zip(rows, data):
        v, E = r["v"], list(r["edges"])
        if v == 1:
            continue
        full = (1 << v) - 1
        # (a) depth N recomputed from the decomposition tree
        def depth(S, ES):
            blocks, host, low = decompose(S, ES)
            return 1 + max([depth(B, [e for e in low if e & B]) if popcount(B) > 1 else 0 for B in blocks])
        if depth(full, E) != r["N"]:
            bad["depth"] += 1
        # (b) |Aut| = product of |Gamma| over the non-leaf components
        if d["autn"] != prod_([h["gamma"] for h in d["hosts"]]):
            bad["aut"] += 1
        # (c) rebuilding of the realization from (host, children)
        h = d["hosts"][0]
        tot = {sum(h["blocks"][i] for i in e) for e in h["host"]} | set(h["low"])
        if tot != set(E):
            bad["rebuild"] += 1
        # (d) Betti numbers: F_2 versus Q, and root host
        bq = betti_over_Q(v, E)
        if bq is not None and bq != d["betti"]:
            bad["betti_Q"] += 1
        if h["m"] >= 2:
            hb = list(compute_betti_numbers(h["m"], [sum(1 << i for i in e) for e in h["host"]], h["m"] - 1))
            while len(hb) > 1 and hb[-1] == 0:
                hb.pop()
            if hb != d["betti"]:
                bad["betti_host"] += 1
        # (e) eccentricity in P(F) = eccentricity of the child in P(root host)
        peK, _, _ = graphs(h["m"], h["host"])
        for i, B in enumerate(h["blocks"]):
            for x in bits(B):
                if d["_pe"][x] != peK[i]:
                    bad["blowup"] += 1
        # (f) delta_I versus delta_P, delta_L
        dP, dL, dI = d["P"][1], d["L"][1], d["I"][1]
        if not (2 * max(dP, dL) <= dI <= 2 * max(dP, dL) + 1):
            bad["dI"] += 1
    names = {"depth": "(a) depth", "aut": "(b) |Aut| = prod |Gamma|", "rebuild": "(c) rebuild",
             "betti_Q": "(d) Betti F2 = Betti Q", "betti_host": "(d) Betti(F) = Betti(root host)",
             "blowup": "(e) blow-up of P", "dI": "(f) bounds on delta_I"}
    ok = True
    for k, nm in names.items():
        log(f"   {nm:<40} {'OK' if not bad[k] else 'FAILURES: ' + str(bad[k])}")
        ok &= not bad[k]
    return ok


def prod_(xs):
    p = 1
    for x in xs:
        p *= x
    return p


def log(*a):
    print(*a, flush=True)


