def symmetry_data(v, E):
    elements = aut_elements_py(v, E)
    parent = list(range(v))

    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a
    for s in elements:
        for x in range(v):
            parent[find(x)] = find(s[x])
    cl = {}
    for x in range(v):
        cl.setdefault(find(x), []).append(x)
    orb = sorted(cl.values())
    return {"order": len(elements), "name": group_name(elements, elements), "orbits": orb,
            "k": len(orb), "inv": [c[0] for c in orb if len(c) == 1], "elements": elements}


