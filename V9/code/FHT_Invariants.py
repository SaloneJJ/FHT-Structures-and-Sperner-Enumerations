def jsonable(x):
    if isinstance(x, Fraction):
        return str(x)
    if isinstance(x, (tuple, list, set, frozenset)):
        return [jsonable(y) for y in x]
    if isinstance(x, dict):
        return {k: jsonable(v) for k, v in x.items() if k not in ("blocks", "low", "host", "_pe")}
    return x


def export(data, outdir):
    os.makedirs(outdir, exist_ok=True)
    p = lambda n: os.path.join(outdir, n)
    json.dump(jsonable(data), open(p("FHT_Inva.json"), "w"))
    with open(p("FHT_Inva_global.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["FHT", "V", "N", "E", "Aut", "|Aut|", "k", "orbits", "|Inv|", "Betti",
                    "P(rho,delta,mean)", "L(rho,delta,mean)", "I(rho,delta,mean)", "edge_orbits"])
        for r in data:
            w.writerow([f"F_{r['id']}", r["v"], r["N"], r["nE"], r["aut"], r["autn"], r["k"], tup(r["orbs"]),
                        r["inv"], tup(r["betti"])] + [("--" if r[g] is None else tup(st(r[g]))) for g in "PLI"]
                       + [tup(r["eorb"])])
    with open(p("FHT_Inva_hosts.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["FHT", "component", "depth", "type", "m", "E(K)", "flat_id", "Gamma", "|Gamma|", "orbits", "|Inv|",
                    "P", "L", "I", "child_profile", "edge_sizes", "edge_weights", "|E(P)|", "|E(L)|", "edge_orbits"])
        for r in data:
            for h in r["hosts"]:
                w.writerow([f"F_{r['id']}", ".".join(map(str, h["path"])) or "root", h["depth"], f"F_{h['ctype']}",
                            h["m"], h["nE"], f"F_{h['flat']}", h["gname"], h["gamma"], tup(h["orbs"]), h["inv"]]
                           + [tup(st(h[g])) for g in "PLI"]
                           + [str([(t, list(sz), mu) for (t, sz), mu in h["profile"]]), tup(h["esz"]), tup(h["ewt"]),
                              h["nP"], h["nL"], tup(h["eorb"])])
    open(p("FHT_Inva_AnnexA.tex"), "w", encoding="utf-8").write(annex_A(data) + "\n")
    open(p("FHT_Inva_AnnexB.tex"), "w", encoding="utf-8").write(annex_B(data) + "\n")
    tab, cls, nf = sep_table(data)
    open(p("FHT_Inva_Separation.tex"), "w", encoding="utf-8").write(tab + "\n")
    json.dump({"classes": {str(k): v for k, v in cls.items()}, "count": {str(k): v for k, v in nf.items()},
               "host_lines": sum(len(r["hosts"]) for r in data)}, open(p("FHT_Inva_stats.json"), "w"), indent=1)
    log(f"written in {outdir}: FHT_Inva.json, _global.csv, _hosts.csv, _AnnexA.tex, _AnnexB.tex, "
        f"_Separation.tex, _stats.json")
    return cls


def main():
    ap = argparse.ArgumentParser(description="FHT invariants (reads the table of FHT_Enumeration.py)")
    ap.add_argument("--table", default=os.path.join(CATALOGUES, "FHT_Table.csv"))
    ap.add_argument("--outdir", default=CATALOGUES)
    a = ap.parse_args()
    log("=" * 70 + "\n FHT_Inva -- invariants of the FHT of the table\n" + "=" * 70)
    if not os.path.exists(a.table):
        sys.exit(f"table not found: {a.table} (run FHT_Enumeration.py first)")
    rows = read_table(a.table)
    vmax = max(r["v"] for r in rows)
    if vmax > 6:
        sys.exit("the pure-Python automorphism search is meant for |V| <= 6")
    log(f"[input] {len(rows)} FHT, 1 <= |V| <= {vmax}")
    data, _ = compute_all(rows)
    log(f"[parameters] global lines: {len(data)};  host lines (all non-leaf components): "
        f"{sum(len(d['hosts']) for d in data)}")
    log("[checks]")
    ok = run_checks(rows, data)
    cls = export(data, a.outdir)
    log("[separation] number of classes, (i)..(vi), all FHT: " + str(cls["tot"]))
    if not ok:
        sys.exit("FAILURE: a check failed")


if __name__ == "__main__":
    main()
