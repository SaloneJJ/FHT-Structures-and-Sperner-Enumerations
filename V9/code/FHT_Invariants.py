def bits(mask):
    i = 0
    while mask:
        if mask & 1:
            yield i
        mask >>= 1
        i += 1


def popcount(x):
    return bin(x).count("1")


def image(mask, perm):
    out, i = 0, 0
    while mask:
        if mask & 1:
            out |= 1 << perm[i]
        mask >>= 1
        i += 1
    return out


def compute_betti_numbers(v, E, N):
    """
    Computes N+1 classical Betti numbers (b_0, b_1, ..., b_N) over F_2 of the simplicial
    complex generated by the hyperedges E on v vertices.
    """
    faces_by_dim = {}
    all_faces = set()
    for e in E:
        elems = list(bits(e))
        for r in range(1, len(elems) + 1):
            for cmb in combinations(elems, r):
                all_faces.add(sum(1 << x for x in cmb))
    for x in range(v):
        all_faces.add(1 << x)

    max_dim = 0
    for f in all_faces:
        d = popcount(f) - 1
        faces_by_dim.setdefault(d, []).append(f)
        max_dim = max(max_dim, d)
    for d in faces_by_dim:
        faces_by_dim[d].sort()

    def rank_f2(matrix, rows, cols):
        if not rows or not cols:
            return 0
        M = [row[:] for row in matrix]
        r = 0
        for c in range(cols):
            pivot = -1
            for i in range(r, rows):
                if M[i][c]:
                    pivot = i
                    break
            if pivot == -1:
                continue
            M[r], M[pivot] = M[pivot], M[r]
            for i in range(rows):
                if i != r and M[i][c]:
                    for j in range(c, cols):
                        M[i][j] ^= M[r][j]
            r += 1
        return r

    ranks = {}
    for d in range(1, max_dim + 2):
        prev_faces = faces_by_dim.get(d - 1, [])
        curr_faces = faces_by_dim.get(d, [])
        if not curr_faces or not prev_faces:
            ranks[d] = 0
            continue
        row_idx = {f: i for i, f in enumerate(prev_faces)}
        matrix = [[0] * len(curr_faces) for _ in range(len(prev_faces))]
        for j, f in enumerate(curr_faces):
            for x in bits(f):
                sub = f ^ (1 << x)
                if sub in row_idx:
                    matrix[row_idx[sub]][j] ^= 1
        ranks[d] = rank_f2(matrix, len(prev_faces), len(curr_faces))

    betti = []
    for k in range(N + 1):
        num_faces = len(faces_by_dim.get(k, []))
        b_k = num_faces - ranks.get(k, 0) - ranks.get(k + 1, 0)
        betti.append(max(0, b_k))
    return tuple(betti)


def _refine(v, E):
    """Label-invariant vertex colours (ranks) by colour refinement on the incidence structure."""
    E = list(E)
    vcol = [tuple(sorted(popcount(e) for e in E if (e >> x) & 1)) for x in range(v)]
    for _ in range(v + 1):
        ecol = [tuple(sorted(vcol[x] for x in bits(e))) for e in E]
        new = [(vcol[x], tuple(sorted(ecol[j] for j, e in enumerate(E) if (e >> x) & 1)))
               for x in range(v)]
        ranks = {c: i for i, c in enumerate(sorted(set(new)))}
        nxt = [ranks[c] for c in new]
        old_ranks = {c: i for i, c in enumerate(sorted(set(vcol)))}
        if len(set(nxt)) == len(set(vcol)):
            vcol = nxt
            break
        vcol = nxt
    ranks = {c: i for i, c in enumerate(sorted(set(vcol)))}
    return [ranks[c] for c in vcol]


def _classes(col):
    cl = {}
    for x, c in enumerate(col):
        cl.setdefault(c, []).append(x)
    return [cl[c] for c in sorted(cl)]


def canon_py(v, E):
    """Canonical form of the hypergraph (v, E): minimum over relabelings compatible with the refinement."""
    col = _refine(v, E)
    classes = _classes(col)
    best = None
    for choice in product(*[list(permutations(c)) for c in classes]):
        order = [x for blk in choice for x in blk]          # new label i <- old vertex order[i]
        pos = {old: new for new, old in enumerate(order)}
        cand = tuple(sorted(sum(1 << pos[x] for x in bits(e)) for e in E))
        if best is None or cand < best:
            best = cand
    return (tuple(sorted(col)), best)


def aut_elements_py(v, E):
    """All automorphisms (as tuples) of the hypergraph (v, E), by search inside colour classes."""
    col = _refine(v, E)
    classes = _classes(col)
    Eset = set(E)
    out = []
    for choice in product(*[list(permutations(c)) for c in classes]):
        sigma = [0] * v
        for cls, perm in zip(classes, choice):
            for a, b in zip(cls, perm):
                sigma[a] = b
        if all(image(e, sigma) in Eset for e in E):
            out.append(tuple(sigma))
    return out


def compose(p, q):
    return tuple(p[q[i]] for i in range(len(q)))


def group_closure(gens, n):
    ident = tuple(range(n))
    elements, frontier = {ident}, [ident]
    while frontier:
        new = []
        for a in frontier:
            for g in gens:
                b = compose(g, a)
                if b not in elements:
                    elements.add(b)
                    new.append(b)
        frontier = new
    return elements


def element_order(p):
    ident, q, k = tuple(range(len(p))), p, 1
    while q != ident:
        q, k = compose(p, q), k + 1
    return k


def group_name(elements, gens):
    n = len(elements)
    o = Counter(element_order(p) for p in elements)
    ab = all(compose(a, b) == compose(b, a) for a in gens for b in gens)
    names = {1: "{e}", 2: "C2", 3: "C3", 5: "C5"}
    if n in names:
        return names[n]
    if n == 4:
        return "C4" if o[4] else "V4"
    if n == 6:
        return "C6" if ab else "S3"
    if n == 8:
        if ab:
            return "C8" if o[8] else ("C4 x C2" if o[4] else "C2^3")
        return "D4" if o[2] == 5 else "Q8"
    if n == 10:
        return "C10" if ab else "D5"
    if n == 12:
        if ab:
            return "C12" if o[12] else "C6 x C2"
        if o[2] == 3 and o[3] == 8:
            return "A4"
        return "D6" if o[2] == 7 else "Dic3"
    if n == 16 and not ab and o[2] == 11:
        return "D4 x C2"
    if n == 24 and o[2] == 9 and o[3] == 8 and o[4] == 6:
        return "S4"
    if n == 48 and not ab and o[2] == 19:
        return "S4 x C2"
    if n == 72 and not ab:
        return "S3 wr C2"
    if n == 120 and o[5] == 24:
        return "S5"
    if n == 720:
        return "S6"
    return f"group of order {n}"

