def compute_all(rows):
    cat = Catalogue(rows)
    data = []
    for r in rows:
        v, E = r["v"], list(r["edges"])
        full = (1 << v) - 1
        rec = dict(id=r["id"], v=v, N=r["N"], nE=len(E))
        assert len(E) == r["nE"], f"F_{r['id']}: |E| differs from the table"
        sd = symmetry_data(v, E)
        rec.update(aut=sd["name"], autn=sd["order"], k=sd["k"], inv=len(sd["inv"]),
                   orbs=sorted((len(o) for o in sd["orbits"]), reverse=True))
        eo, seen = [], set()
        for e in E:
            if e in seen:
                continue
            o = {image(e, p) for p in sd["elements"]}
            seen |= o
            eo.append(len(o))
        rec["eorb"] = sorted(eo, reverse=True)
        b = list(compute_betti_numbers(v, E, v - 1))
        while len(b) > 1 and b[-1] == 0:
            b.pop()
        rec["betti"] = b
        if v == 1:
            rec.update(P=None, L=None, I=None, hosts=[])
        else:
            pe, le, ie = graphs(v, [frozenset(bits(e)) for e in E])
            rec.update(P=stat(pe), L=stat(le), I=stat(ie))
            hosts = []
            for path, S, ES, d in nodes_of(cat, full, E):
                hl = host_line(cat, S, ES)
                hl.update(path=path, depth=d, size=popcount(S), ctype=cat.typ(S, ES))
                hosts.append(hl)
            assert hosts[0]["ctype"] == r["id"]
            rec["hosts"] = hosts
            rec["_pe"] = pe
        data.append(rec)
    return data, cat


